// §11: entry n + 0 is %0000RRRR, entry n + 1 is %GGGGBBBB, into the window's
// 512 bytes.
void vdp_palette_install(uint8_t *window) {
    for (unsigned entry = 0; entry < VDP_PALETTE_ENTRIES; entry++) {
        uint16_t rgb = vdp_default_palette[entry];
        window[2 * entry] = (uint8_t)((rgb >> 8) & 0x0f);
        window[2 * entry + 1] = (uint8_t)rgb;
    }
}

// $RGB, as stored, to the DAC's 0x0BGR (§2: 4-4-4 on GPIO 2-13), paired for
// the ×2 expansion — the way pico9918 doubles horizontally.
void VDP_HOT(vdp_palette_cache_entry)(vdp_t *v, unsigned entry) {
    uint16_t rgb = vdp_palette_decode(v->render_vram, vdp_palette_base(v->render_reg), entry);
    uint32_t bgr = (uint32_t)((rgb >> 8) & 0x0f) | (rgb & 0x0f0u) | ((uint32_t)(rgb & 0x0f) << 8);
    v->palette[entry] = bgr * 0x10001u;
}

void vdp_palette_reload(vdp_t *v) {
    for (unsigned entry = 0; entry < VDP_PALETTE_ENTRIES; entry++) vdp_palette_cache_entry(v, entry);
}
